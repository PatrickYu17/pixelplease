import opentype from "opentype.js";
import {
  createCellMaskFromImageData,
  expandCellMask,
  isCellFilled,
  type CellMask,
} from "./pixel-grid";

export { expandCellMask as dilateMask, type CellMask } from "./pixel-grid";

export type PixelizeOptions = {
  pixelsPerEm: number;
  threshold: number;
  expand: number;
  shiftX?: number;
  shiftY?: number;
  pixelShape?: PixelShape;
};

export type PixelShape = "square" | "round" | "vertical-lines" | "horizontal-lines";

export type FontMetrics = {
  unitsPerEm: number;
  ascender: number;
  descender: number;
};

export type PixelGrid = {
  cellSize: number;
  top: number;
  bottom: number;
  rows: number;
};

export type CellOrigin = {
  left?: number;
  top?: number;
};

type GlyphBounds = {
  x1: number;
  y1: number;
  x2: number;
  y2: number;
};

export type CoverageItem = {
  codePoint: number;
  char: string;
  supported: boolean;
};

export type PixelizeResult = {
  font: opentype.Font;
  arrayBuffer: ArrayBuffer;
  glyphCount: number;
  familyName: string;
  styleName: string;
  fullName: string;
  postScriptName: string;
};

export type PixelizeMetadata = {
  sourceLicenseUrl?: string;
  fontNames?: PixelizeFontNames;
};

export type PixelizeFontNames = {
  familyName: string;
  styleName: string;
  fullName?: string;
  postScriptName?: string;
};

const BASIC_LATIN_START = 32;
const BASIC_LATIN_END = 126;
const DERIVATIVE_FAMILY_NAME = "PixelPlease Generated";
const DERIVATIVE_STYLE_NAME = "Regular";
const MIN_PIXELS_PER_EM = 8;
const MAX_PIXELS_PER_EM = 64;

export function parseFont(buffer: ArrayBuffer): opentype.Font {
  return opentype.parse(buffer);
}

export function getFontLabel(font: opentype.Font): string {
  return `${getFontFamilyName(font)} ${getFontStyleName(font)}`.trim();
}

export function getFontFamilyName(font: opentype.Font): string {
  return readName(font, "preferredFamily") || readName(font, "fontFamily") || "Uploaded Font";
}

export function getFontStyleName(font: opentype.Font): string {
  return readName(font, "preferredSubfamily") || readName(font, "fontSubfamily") || "Regular";
}

function makeDerivativeFontNames(metadata: PixelizeMetadata): Required<PixelizeFontNames> {
  const familyName = metadata.fontNames?.familyName || DERIVATIVE_FAMILY_NAME;
  const styleName = metadata.fontNames?.styleName || DERIVATIVE_STYLE_NAME;
  const fullName = metadata.fontNames?.fullName || `${familyName} ${styleName}`.trim();
  const postScriptName = metadata.fontNames?.postScriptName || makePostScriptName(fullName);

  return {
    familyName,
    styleName,
    fullName,
    postScriptName,
  };
}

function makePostScriptName(value: string): string {
  return value.replace(/[^a-zA-Z0-9]+/g, "-").replace(/^-+|-+$/g, "") || "PixelPlease-Generated-Regular";
}

export function getBasicLatinCoverage(font: opentype.Font): CoverageItem[] {
  const items: CoverageItem[] = [];

  for (let codePoint = BASIC_LATIN_START; codePoint <= BASIC_LATIN_END; codePoint += 1) {
    const char = String.fromCharCode(codePoint);
    const glyphIndex = font.charToGlyphIndex(char);
    items.push({
      codePoint,
      char,
      supported: codePoint === 32 || glyphIndex > 0,
    });
  }

  return items;
}

export async function pixelizeFont(
  sourceFont: opentype.Font,
  options: PixelizeOptions,
  onProgress?: (done: number, total: number) => void,
  metadata: PixelizeMetadata = {},
): Promise<PixelizeResult> {
  await nextFrame();

  const metrics = getMetrics(sourceFont);
  const fontNames = makeDerivativeFontNames(metadata);
  const coverage = getBasicLatinCoverage(sourceFont).filter((item) => item.supported);
  const sourceGlyphs = coverage.map((item) => sourceFont.charToGlyph(item.char));
  const grid = getPixelGrid(sourceGlyphs, metrics, options);
  const glyphs: opentype.Glyph[] = [createNotDefGlyph(metrics, options, grid)];

  for (let index = 0; index < coverage.length; index += 1) {
    const item = coverage[index];
    const glyph = sourceGlyphs[index];
    glyphs.push(pixelizeGlyph(glyph, item.codePoint, metrics, options, grid));
    onProgress?.(index + 1, coverage.length);

    if (index % 12 === 0) {
      await nextFrame();
    }
  }

  const pixelFont = new opentype.Font({
    familyName: fontNames.familyName,
    styleName: fontNames.styleName,
    fullName: fontNames.fullName,
    postScriptName: fontNames.postScriptName,
    unitsPerEm: metrics.unitsPerEm,
    ascender: grid.top,
    descender: grid.bottom,
    manufacturer: "pixelplease",
    license:
      "Generated derivative. Source font license controls use, modification, and redistribution.",
    ...(metadata.sourceLicenseUrl ? { licenseURL: metadata.sourceLicenseUrl } : {}),
    version: "Version 0.1; generated by pixelplease",
    description:
      "Generated by pixelplease from a source font. Font names use PixelPlease plus a compact source code, effect recipe, short hash, and style.",
    copyright:
      "Generated by pixelplease. Source font copyright and license terms remain with the source font owner.",
    glyphs,
  });

  return {
    font: pixelFont,
    arrayBuffer: pixelFont.toArrayBuffer(),
    glyphCount: glyphs.length,
    familyName: fontNames.familyName,
    styleName: fontNames.styleName,
    fullName: fontNames.fullName,
    postScriptName: fontNames.postScriptName,
  };
}

function pixelizeGlyph(
  sourceGlyph: opentype.Glyph,
  codePoint: number,
  metrics: FontMetrics,
  options: PixelizeOptions,
  grid: PixelGrid,
): opentype.Glyph {
  const advanceWidth = Math.max(0, sourceGlyph.advanceWidth || metrics.unitsPerEm * 0.5);

  if (codePoint === 32 || sourceGlyph.index === 0) {
    const spaceGlyph = new opentype.Glyph({
      name: glyphName(codePoint),
      unicode: codePoint,
      advanceWidth: snapAdvance(advanceWidth, metrics, options),
      path: new opentype.Path(),
    });
    spaceGlyph.leftSideBearing = 0;
    return spaceGlyph;
  }

  const { mask, left } = rasterizeGlyphToCells(sourceGlyph, metrics, options, grid);
  const expandedMask = expandCellMask(mask, options.expand);
  const path = cellsToPath(expandedMask, metrics, options, { left, top: grid.top });
  const pathBounds = path.getBoundingBox();
  const glyph = new opentype.Glyph({
    name: glyphName(codePoint),
    unicode: codePoint,
    advanceWidth: snapAdvance(advanceWidth, metrics, options),
    path,
  });

  glyph.leftSideBearing = Number.isFinite(pathBounds.x1) ? pathBounds.x1 : 0;
  return glyph;
}

export function cellsToPath(
  mask: CellMask,
  metrics: FontMetrics,
  options: PixelizeOptions,
  origin: CellOrigin = {},
): opentype.Path {
  const path = new opentype.Path();
  const cellSize = getCellSize(metrics, options);
  const left = origin.left ?? 0;
  const top = origin.top ?? metrics.ascender;

  if (options.pixelShape === "round") {
    addRoundCellsToPath(path, mask, cellSize, left, top);
    return path;
  }

  if (options.pixelShape === "vertical-lines" || options.pixelShape === "horizontal-lines") {
    addLineCellsToPath(path, mask, cellSize, left, top, options.pixelShape);
    return path;
  }

  for (let row = 0; row < mask.rows; row += 1) {
    let col = 0;

    while (col < mask.cols) {
      while (col < mask.cols && !isCellFilled(mask, col, row)) {
        col += 1;
      }

      if (col >= mask.cols) {
        break;
      }

      const start = col;
      while (col < mask.cols && isCellFilled(mask, col, row)) {
        col += 1;
      }

      const end = col;
      const x0 = left + start * cellSize;
      const x1 = left + end * cellSize;
      const yTop = top - row * cellSize;
      const yBottom = yTop - cellSize;
      addRect(path, x0, yBottom, x1, yTop);
    }
  }

  return path;
}

function addRoundCellsToPath(
  path: opentype.Path,
  mask: CellMask,
  cellSize: number,
  left: number,
  top: number,
): void {
  for (let row = 0; row < mask.rows; row += 1) {
    for (let col = 0; col < mask.cols; col += 1) {
      if (!isCellFilled(mask, col, row)) {
        continue;
      }

      const x0 = left + col * cellSize;
      const x1 = x0 + cellSize;
      const yTop = top - row * cellSize;
      const yBottom = yTop - cellSize;
      addEllipse(path, x0, yBottom, x1, yTop);
    }
  }
}

function addLineCellsToPath(
  path: opentype.Path,
  mask: CellMask,
  cellSize: number,
  left: number,
  top: number,
  pixelShape: Extract<PixelShape, "vertical-lines" | "horizontal-lines">,
): void {
  const inset = Math.round(cellSize * 0.28);

  for (let row = 0; row < mask.rows; row += 1) {
    for (let col = 0; col < mask.cols; col += 1) {
      if (!isCellFilled(mask, col, row)) {
        continue;
      }

      const x0 = left + col * cellSize;
      const x1 = x0 + cellSize;
      const yTop = top - row * cellSize;
      const yBottom = yTop - cellSize;

      if (pixelShape === "vertical-lines") {
        addRect(path, x0 + inset, yBottom, x1 - inset, yTop);
      } else {
        addRect(path, x0, yBottom + inset, x1, yTop - inset);
      }
    }
  }
}

function getMetrics(font: opentype.Font): FontMetrics {
  const unitsPerEm = font.unitsPerEm || 1000;
  return {
    unitsPerEm,
    ascender: font.ascender || Math.round(unitsPerEm * 0.8),
    descender: font.descender || -Math.round(unitsPerEm * 0.2),
  };
}

function getCellSize(metrics: FontMetrics, options: PixelizeOptions): number {
  return metrics.unitsPerEm / getGridPixelsPerEm(metrics, options);
}

export function getGridPixelsPerEm(metrics: FontMetrics, options: PixelizeOptions): number {
  const requested = Math.round(clamp(options.pixelsPerEm, MIN_PIXELS_PER_EM, MAX_PIXELS_PER_EM));
  const divisors: number[] = [];

  for (let divisor = MIN_PIXELS_PER_EM; divisor <= MAX_PIXELS_PER_EM; divisor += 1) {
    if (metrics.unitsPerEm % divisor === 0) {
      divisors.push(divisor);
    }
  }

  if (divisors.length === 0) {
    return requested;
  }

  return divisors.reduce((best, current) => {
    const bestDistance = Math.abs(best - requested);
    const currentDistance = Math.abs(current - requested);
    return currentDistance < bestDistance || (currentDistance === bestDistance && current > best) ? current : best;
  }, divisors[0]);
}

function rasterizeGlyphToCells(
  sourceGlyph: opentype.Glyph,
  metrics: FontMetrics,
  options: PixelizeOptions,
  grid: PixelGrid,
): { mask: CellMask; left: number } {
  const cellSize = grid.cellSize;
  const advanceWidth = Math.max(cellSize, sourceGlyph.advanceWidth || metrics.unitsPerEm * 0.5);
  const samplesPerCell = 5;
  const scale = samplesPerCell / cellSize;
  const expand = Math.max(0, Math.ceil(options.expand));
  const shiftXUnits = clamp(options.shiftX ?? 0, -0.5, 0.5) * cellSize;
  const shiftYUnits = clamp(options.shiftY ?? 0, -0.5, 0.5) * cellSize;
  const bounds = getGlyphBounds(sourceGlyph);

  // The source glyph may paint outside its advance width and outside the
  // font's declared ascender/descender. Rasterize the real ink extent (plus
  // grid shift and dilation room) so no part of the glyph is clipped.
  const inkLeft = Math.min(0, bounds?.x1 ?? 0) + shiftXUnits;
  const inkRight = Math.max(advanceWidth, bounds?.x2 ?? advanceWidth) + shiftXUnits;
  const left = Math.floor(inkLeft / cellSize) * cellSize - expand * cellSize;
  const right = Math.ceil(inkRight / cellSize) * cellSize + expand * cellSize;
  const cols = Math.max(1, Math.round((right - left) / cellSize));
  const canvas = document.createElement("canvas");
  canvas.width = cols * samplesPerCell;
  canvas.height = grid.rows * samplesPerCell;

  const context = canvas.getContext("2d", { willReadFrequently: true });
  if (!context) {
    throw new Error("Could not create canvas context for glyph rasterization.");
  }

  context.clearRect(0, 0, canvas.width, canvas.height);
  context.fillStyle = "#000";
  sourceGlyph.draw(
    context,
    (shiftXUnits - left) * scale,
    (grid.top + shiftYUnits) * scale,
    metrics.unitsPerEm * scale,
  );

  const threshold = clamp(options.threshold, 0.05, 0.95);

  return {
    left,
    mask: createCellMaskFromImageData({
      data: context.getImageData(0, 0, canvas.width, canvas.height).data,
      width: canvas.width,
      height: canvas.height,
      cellSize: samplesPerCell,
      threshold,
      mode: "alpha",
    }),
  };
}

export function getPixelGrid(
  sourceGlyphs: opentype.Glyph[],
  metrics: FontMetrics,
  options: PixelizeOptions,
): PixelGrid {
  const cellSize = getCellSize(metrics, options);
  const expand = Math.max(0, Math.ceil(options.expand));
  const shiftYUnits = clamp(options.shiftY ?? 0, -0.5, 0.5) * cellSize;
  let inkTop = metrics.ascender;
  let inkBottom = metrics.descender;

  for (const glyph of sourceGlyphs) {
    const bounds = getGlyphBounds(glyph);
    if (!bounds) {
      continue;
    }

    inkTop = Math.max(inkTop, bounds.y2 - shiftYUnits);
    inkBottom = Math.min(inkBottom, bounds.y1 - shiftYUnits);
  }

  const top = Math.ceil(inkTop / cellSize) * cellSize + expand * cellSize;
  const bottom = Math.floor(inkBottom / cellSize) * cellSize - expand * cellSize;
  const rows = Math.max(1, Math.round((top - bottom) / cellSize));

  return { cellSize, top, bottom, rows };
}

function getGlyphBounds(glyph: opentype.Glyph): GlyphBounds | null {
  const bounds = glyph.getBoundingBox();
  if (
    !Number.isFinite(bounds.x1) ||
    !Number.isFinite(bounds.y1) ||
    !Number.isFinite(bounds.x2) ||
    !Number.isFinite(bounds.y2)
  ) {
    return null;
  }

  return bounds;
}

function createNotDefGlyph(metrics: FontMetrics, options: PixelizeOptions, grid: PixelGrid): opentype.Glyph {
  const cellSize = getCellSize(metrics, options);
  const path = new opentype.Path();
  const width = Math.round(metrics.unitsPerEm * 0.5 / cellSize) * cellSize;
  const top = grid.top;
  const bottom = grid.bottom;

  addRect(path, 0, bottom, width, top);
  addRect(path, cellSize, bottom + cellSize, width - cellSize, top - cellSize, true);

  return new opentype.Glyph({
    name: ".notdef",
    advanceWidth: width + cellSize,
    path,
  });
}

function addRect(path: opentype.Path, x0: number, y0: number, x1: number, y1: number, reverse = false): void {
  if (reverse) {
    path.moveTo(x0, y0);
    path.lineTo(x0, y1);
    path.lineTo(x1, y1);
    path.lineTo(x1, y0);
    path.close();
    return;
  }

  path.moveTo(x0, y0);
  path.lineTo(x1, y0);
  path.lineTo(x1, y1);
  path.lineTo(x0, y1);
  path.close();
}

function addEllipse(path: opentype.Path, x0: number, y0: number, x1: number, y1: number): void {
  const kappa = 0.5522847498307936;
  const cx = (x0 + x1) / 2;
  const cy = (y0 + y1) / 2;
  const rx = (x1 - x0) / 2;
  const ry = (y1 - y0) / 2;

  path.moveTo(cx + rx, cy);
  path.curveTo(cx + rx, cy + ry * kappa, cx + rx * kappa, cy + ry, cx, cy + ry);
  path.curveTo(cx - rx * kappa, cy + ry, cx - rx, cy + ry * kappa, cx - rx, cy);
  path.curveTo(cx - rx, cy - ry * kappa, cx - rx * kappa, cy - ry, cx, cy - ry);
  path.curveTo(cx + rx * kappa, cy - ry, cx + rx, cy - ry * kappa, cx + rx, cy);
  path.close();
}

function snapAdvance(advanceWidth: number, metrics: FontMetrics, options: PixelizeOptions): number {
  const cellSize = getCellSize(metrics, options);
  return Math.max(cellSize, Math.ceil(advanceWidth / cellSize) * cellSize);
}

function glyphName(codePoint: number): string {
  return `u${codePoint.toString(16).toUpperCase().padStart(4, "0")}`;
}

function readName(font: opentype.Font, key: string): string | undefined {
  const names = font.names as unknown as Record<string, Record<string, string> | undefined>;
  return names[key]?.en || Object.values(names[key] || {})[0];
}

function clamp(value: number, min: number, max: number): number {
  return Math.max(min, Math.min(max, value));
}

function nextFrame(): Promise<void> {
  return new Promise((resolve) => requestAnimationFrame(() => resolve()));
}
